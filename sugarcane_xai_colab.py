def set_seed(seed: int, deterministic: bool = True) -> None:
    """Seed Python, NumPy, PyTorch (CPU+CUDA).

    Limitation: even with fixed seeds, some CUDA kernels (atomic adds in certain backward passes,
    AMP fp16 accumulation, non-deterministic cuDNN algorithms) can produce tiny run-to-run differences.
    We set cudnn.deterministic=True and benchmark=False, but full bitwise reproducibility is not guaranteed
    across GPU types, driver/library versions, or DataLoader worker counts.
    """
    random.seed(seed)
    np.random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = deterministic
    torch.backends.cudnn.benchmark = not deterministic


