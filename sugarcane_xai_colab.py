_AUG_TOKEN = re.compile(
    r"([_\-\s]?(aug(mented)?|copy|rot(ated)?|flip(ped)?|mirror)[_\-]?\d*)|(\(\d+\))|([_\-]\d+$)",
    re.I,
)


def assign_groups(df: pd.DataFrame, group_by_filename: bool = True) -> pd.DataFrame:
    """Assign leakage-groups: byte-identical files (md5) and, optionally, filename variants
    (same class + same stem after removing augmentation tokens like _aug1, _copy, (2)) share a group id."""
    parent = list(range(len(df)))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    def union(i, j):
        ri, rj = find(i), find(j)
        if ri != rj:
            parent[rj] = ri

    keys = [df["md5"].tolist()]
    if group_by_filename:
        keys.append(
            [
                f"{c}|{_AUG_TOKEN.sub('', Path(p).stem).lower()}"
                for c, p in zip(df.class_name, df.path)
            ]
        )

    for key_list in keys:
        first: Dict[str, int] = {}
        for i, k in enumerate(key_list):
            if k in first:
                union(first[k], i)
            else:
                first[k] = i

    df = df.copy()
    df["group_id"] = [find(i) for i in range(len(df))]
    sizes = df["group_id"].map(df["group_id"].value_counts())
    n_multi = df.loc[sizes > 1, "group_id"].nunique()
    print(
        f"Leakage groups: {df.group_id.nunique()} groups; {n_multi} contain >1 image ({int((sizes > 1).sum())} images)."
    )
    if n_multi == 0:
        print(
            "  No duplicate/variant grouping information found -> near-duplicate leakage cannot be excluded "
            "if the dataset contains pre-augmented copies with unrelated filenames."
        )
    return df


def _group_holdout(
    df: pd.DataFrame, frac: float, seed: int
) -> Tuple[np.ndarray, np.ndarray]:
    """Stratified, group-aware holdout of ~frac of df. Returns (rest_idx, holdout_idx) as positional indices."""
    n_splits = max(2, int(round(1.0 / frac)))
    sgkf = StratifiedGroupKFold(n_splits=n_splits, shuffle=True, random_state=seed)
    rest, hold = next(sgkf.split(df, df["label"], df["group_id"]))
    return rest, hold


def create_splits(
    df: pd.DataFrame,
    val_frac: float,
    test_frac: float,
    seed: int,
    group_by_filename: bool = True,
) -> pd.DataFrame:
    """Stratified + group-aware train/val/test split with leakage checks. Adds a 'split' column."""
    if df["class_name"].value_counts().min() < 10:
        warnings.warn("A class has <10 images; stratified splits will be very small.")

    df = assign_groups(df, group_by_filename).reset_index(drop=True)

    rest_idx, test_idx = _group_holdout(df, test_frac, seed)
    rest = df.iloc[rest_idx].reset_index(drop=True)

    tr_idx, va_idx = _group_holdout(rest, val_frac / (1.0 - test_frac), seed)

    df["split"] = ""
    df.loc[df.index[test_idx], "split"] = "test"

    rest_paths_val = set(rest.iloc[va_idx]["path"])
    rest_paths_tr = set(rest.iloc[tr_idx]["path"])

    df.loc[df["path"].isin(rest_paths_val), "split"] = "val"
    df.loc[df["path"].isin(rest_paths_tr), "split"] = "train"

    # Print summary & verify no group leakage across splits
    counts = pd.crosstab(df["class_name"], df["split"])
    print("\n=== SPLIT SUMMARY ===")
    print(counts)
    print("\nSplit proportions:")
    print((df["split"].value_counts(normalize=True) * 100).round(2).to_string())

    # Verify zero leakage across groups
    train_groups = set(df[df["split"] == "train"]["group_id"])
    val_groups = set(df[df["split"] == "val"]["group_id"])
    test_groups = set(df[df["split"] == "test"]["group_id"])

    assert len(train_groups & val_groups) == 0, "Leakage detected between train and val!"
    assert len(train_groups & test_groups) == 0, "Leakage detected between train and test!"
    assert len(val_groups & test_groups) == 0, "Leakage detected between val and test!"
    print("\n✓ No group leakage detected between train, val, and test splits.")

    return df


