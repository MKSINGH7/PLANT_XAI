def resolve_timm_name(model_name: str, cfg: dict = CONFIG) -> str:
    if model_name == "convnext_tiny":
        return "convnext_tiny"
    if model_name == "efficientnetv2_s":
        return "tf_efficientnetv2_s"   # NB: timm's default tf_ weights were trained with mean/std 0.5; we still use ImageNet stats (see warning)
    if model_name == "mobilenetv4":
        return cfg["MOBILENETV4_VARIANT"]
    raise ValueError(f"Unknown model_name '{model_name}'. Supported: convnext_tiny, efficientnetv2_s, mobilenetv4")


def create_model(model_name: str, num_classes: int, pretrained: bool = True, cfg: dict = CONFIG) -> nn.Module:
    """Create a timm model with a fresh classifier of size `num_classes`."""
    timm_name = resolve_timm_name(model_name, cfg)
    available = timm.list_models()
    if timm_name not in available:
        if model_name == "mobilenetv4":
            found = timm.list_models("*mobilenetv4*")
            msg = (f"MobileNetV4 variant '{timm_name}' not available in timm {timm.__version__}. "
                   f"MobileNetV4-like models found: {found or 'NONE'}. "
                   + ("Set CONFIG['MOBILENETV4_VARIANT'] to one of these." if found else
                      "Your timm is too old: run `pip install -U 'timm>=1.0.9'` and restart the runtime."))
            raise RuntimeError(msg)
        raise RuntimeError(f"timm model '{timm_name}' not found in timm {timm.__version__}.")
    try:
        model = timm.create_model(timm_name, pretrained=pretrained, num_classes=num_classes)
    except Exception as e:  # noqa: BLE001
        raise RuntimeError(f"Failed to create '{timm_name}' (pretrained={pretrained}). If this is a download error, "
                           f"check internet access / HF hub availability. Original: {e}") from e
    out_features = model.get_classifier().out_features
    if out_features != num_classes:
        raise RuntimeError(f"Classifier replacement failed: {out_features} outputs, expected {num_classes}.")
    pc = getattr(model, "pretrained_cfg", {}) or {}
    if pretrained and pc.get("mean") is not None and not np.allclose(pc["mean"], IMAGENET_MEAN, atol=1e-3):
        print(f"  WARNING: {timm_name} pretrained weights expect mean={pc['mean']}, std={pc.get('std')}, "
              f"but the pipeline uses ImageNet stats {IMAGENET_MEAN}/{IMAGENET_STD} as specified. "
              f"Fine-tuning will adapt, but be aware of the mismatch.")
    model.meta = {"model_name": model_name, "timm_name": timm_name}
    return model


