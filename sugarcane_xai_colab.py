# CELL 15 — XAI target-layer detection
def _layer_name(model: nn.Module, layer: nn.Module) -> str:
    for n, m in model.named_modules():
        if m is layer:
            return n
    return layer.__class__.__name__


def validate_target_layer(model: nn.Module, layer: nn.Module, image_size: int) -> Tuple[int, ...]:
    """Dry-run forward pass to confirm the layer emits a 4-D spatial tensor (B,C,H,W) with H,W > 1."""
    cap: Dict[str, torch.Tensor] = {}
    h = layer.register_forward_hook(lambda m, i, o: cap.setdefault("o", o))
    was_training = model.training
    model.eval()
    try:
        dev = next(model.parameters()).device
        with torch.no_grad():
            model(torch.zeros(1, 3, image_size, image_size, device=dev))
    finally:
        h.remove()
        model.train(was_training)
    out = cap.get("o")
    if not isinstance(out, torch.Tensor) or out.ndim != 4 or min(out.shape[-2:]) <= 1:
        shape = tuple(out.shape) if isinstance(out, torch.Tensor) else type(out).__name__
        raise RuntimeError(f"Invalid CAM target layer '{_layer_name(model, layer)}': output {shape} is not a "
                           f"spatial (B,C,H,W) feature map.")
    return tuple(out.shape)


def get_target_layers(model: nn.Module, model_name: str, image_size: Optional[int] = None, verbose: bool = True) -> List[nn.Module]:
    """Model-specific final spatial feature layer for CAM methods (validated with a dry run).

    convnext_tiny    -> model.stages[-1]      (last ConvNeXt stage, 7x7 for 224 input)
    efficientnetv2_s -> model.blocks[-1][-1]  (last MBConv/FusedMBConv block before conv_head)
    mobilenetv4      -> model.blocks[-1]      (last feature stage before conv_head/pooling)
    """
    meta = getattr(model, "meta", {})
    image_size = image_size or meta.get("image_size", CONFIG["IMAGE_SIZE"])
    cached = meta.get("target_layers")
    if cached is not None:
        return cached
    try:
        if model_name == "convnext_tiny":
            layer = model.stages[-1]
        elif model_name == "efficientnetv2_s":
            layer = model.blocks[-1][-1]
        elif model_name == "mobilenetv4":
            layer = model.blocks[-1]
        else:
            raise ValueError(f"No target-layer rule for model '{model_name}'.")
    except (AttributeError, IndexError, TypeError) as e:
        raise RuntimeError(f"Could not locate target layer for '{model_name}' in timm model "
                           f"{model.__class__.__name__}: {e}") from e
    shape = validate_target_layer(model, layer, image_size)
    if verbose:
        print(f"[target layer] {model_name}: '{_layer_name(model, layer)}' -> {layer.__class__.__name__}, output shape {shape}")
    meta["target_layers"] = [layer]
    model.meta = meta
    return [layer]


