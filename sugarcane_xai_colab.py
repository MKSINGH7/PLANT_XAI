# CELL 7 — Dataset and augmentation pipeline
def build_transforms(image_size: int, train: bool, cfg: dict = CONFIG) -> A.Compose:
    """Train: mild geometric + colour augmentation. Val/test/inference: deterministic resize + normalize only."""
    ops: list = [A.Resize(height=image_size, width=image_size)]
    if train:
        j = cfg["AUG_COLOR_JITTER"]
        ops += [
            A.HorizontalFlip(p=0.5),
            A.Affine(scale=tuple(cfg["AUG_SCALE"]), rotate=(-cfg["AUG_ROTATE_DEG"], cfg["AUG_ROTATE_DEG"]), p=0.5),
            A.ColorJitter(brightness=j, contrast=j, saturation=j, hue=0.02, p=0.5),
        ]
    ops += [A.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD), ToTensorV2()]
    return A.Compose(ops)


class PlantDiseaseDataset(Dataset):
    """Reads RGB images from a DataFrame with columns 'path' and 'label'."""

    def __init__(self, df: pd.DataFrame, transform: A.Compose):
        self.paths = df["path"].tolist()
        self.labels = df["label"].astype(int).tolist()
        self.transform = transform

    def __len__(self) -> int:
        return len(self.paths)

    def __getitem__(self, i: int):
        img = np.array(Image.open(self.paths[i]).convert("RGB"))
        x = self.transform(image=img)["image"]
        return x, self.labels[i]


def _worker_init_fn(worker_id: int) -> None:
    seed = torch.initial_seed() % 2**32
    random.seed(seed)
    np.random.seed(seed)
    info = get_worker_info()
    tf = getattr(info.dataset, "transform", None) if info else None
    if tf is not None and hasattr(tf, "set_random_seed"):   # albumentations >= 2.x
        try:
            tf.set_random_seed(seed)
        except Exception:  # noqa: BLE001
            pass


def make_loader(df: pd.DataFrame, train: bool, cfg: dict = CONFIG) -> DataLoader:
    ds = PlantDiseaseDataset(df, build_transforms(cfg["IMAGE_SIZE"], train, cfg))
    g = torch.Generator().manual_seed(cfg["SEED"])
    nw = cfg["NUM_WORKERS"]
    return DataLoader(ds, batch_size=cfg["BATCH_SIZE"], shuffle=train, drop_last=False, num_workers=nw,
                      pin_memory=(device.type == "cuda"), persistent_workers=(nw > 0),
                      worker_init_fn=_worker_init_fn, generator=g)


def compute_class_weights(train_df: pd.DataFrame, n_classes: int) -> torch.Tensor:
    counts = np.bincount(train_df["label"].astype(int), minlength=n_classes).astype(np.float64)
    w = counts.sum() / (n_classes * np.maximum(counts, 1))
    return torch.tensor(w, dtype=torch.float32)

