# CELL 18 — Batch XAI visualization
def run_xai_batch(model_name: str, checkpoint_path, test_df: pd.DataFrame, n: int, seed: int,
                  methods: Sequence[str] = ("gradcam++", "layercam", "eigencam")) -> pd.DataFrame:
    """Explain N randomly chosen test images (fixed seed) with one model; writes xai/<model>/image_XXX/."""
    model = _get_model(model_name, checkpoint_path)
    layer = get_target_layers(model, model_name, verbose=False)[0]
    print(f"[target layer] {model_name}: '{_layer_name(model, layer)}'")
    test_df = test_df.reset_index(drop=True)
    idxs = random.Random(seed).sample(range(len(test_df)), min(n, len(test_df)))
    rows = []
    for k, i in enumerate(tqdm(idxs, desc=f"XAI {model_name}"), start=1):
        r = test_df.iloc[i]
        info = explain_loaded(model, r["path"], methods, DIRS["xai"] / model_name / f"image_{k:03d}", r["class_name"])
        rows.append(info)
    manifest = pd.DataFrame(rows)
    manifest.to_csv(DIRS["xai"] / model_name / "xai_manifest.csv", index=False)
    return manifest


