def load_rgb(image: Union[str, Path, Image.Image, np.ndarray]) -> np.ndarray:
    if isinstance(image, (str, Path)):
        if not Path(image).exists():
            raise FileNotFoundError(f"Image not found: {image}")
        return np.array(Image.open(image).convert("RGB"))
    if isinstance(image, Image.Image):
        return np.array(image.convert("RGB"))
    arr = np.asarray(image)
    if arr.ndim != 3 or arr.shape[2] != 3:
        raise ValueError(f"Expected HxWx3 RGB array, got {arr.shape}")
    return arr.astype(np.uint8)


def preprocess_image(image, image_size: int, mean: Sequence[float], std: Sequence[float]) -> Tuple[torch.Tensor, np.ndarray]:
    """Same deterministic preprocessing as validation/test. Returns (tensor[1,3,S,S], resized RGB float32 in [0,1])."""
    rgb = load_rgb(image)
    tf = A.Compose([A.Resize(height=image_size, width=image_size), A.Normalize(mean=mean, std=std), ToTensorV2()])
    tensor = tf(image=rgb)["image"].unsqueeze(0)
    resized = cv2.resize(rgb, (image_size, image_size), interpolation=cv2.INTER_LINEAR)
    return tensor, resized.astype(np.float32) / 255.0


@torch.no_grad()
def predict_tensor(model: nn.Module, tensor: torch.Tensor) -> Tuple[int, float, np.ndarray]:
    model.eval()
    probs = torch.softmax(model(tensor.to(device)).float(), 1)[0].cpu().numpy()
    idx = int(probs.argmax())
    return idx, float(probs[idx]), probs


def _resolve_target(target_class, class_names: List[str]) -> Optional[int]:
    if target_class is None:
        return None
    if isinstance(target_class, str):
        if target_class not in class_names:
            raise ValueError(f"Unknown target_class '{target_class}'. Known: {class_names}")
        return class_names.index(target_class)
    if not 0 <= int(target_class) < len(class_names):
        raise ValueError(f"target_class index {target_class} out of range [0,{len(class_names) - 1}]")
    return int(target_class)


def generate_xai(model: nn.Module, tensor: torch.Tensor, rgb_float: np.ndarray, method: str,
                 target_layers: List[nn.Module], target_idx: Optional[int] = None) -> Tuple[np.ndarray, np.ndarray]:
    """Run one CAM method. Returns (heatmap[H,W] in [0,1], overlay uint8 RGB).

    target_idx=None -> explain the model's predicted class. NOTE: Eigen-CAM is class-agnostic (first principal
    component of the activations) and ignores the target; Grad-CAM++/Layer-CAM explain the target class.
    """
    method = method.lower()
    if method not in CAM_REGISTRY:
        raise ValueError(f"Unsupported XAI method '{method}'. Supported: {list(CAM_REGISTRY)}")
    cls = CAM_REGISTRY[method]
    kwargs = {"model": model, "target_layers": target_layers}
    if "use_cuda" in inspect.signature(cls.__init__).parameters:      # older pytorch-grad-cam versions
        kwargs["use_cuda"] = device.type == "cuda"
    targets = [ClassifierOutputTarget(target_idx)] if target_idx is not None else None
    model.eval()
    cam = cls(**kwargs)
    try:
        with torch.enable_grad():
            gray = cam(input_tensor=tensor.to(device), targets=targets)[0]
    except Exception as e:  # noqa: BLE001
        raise RuntimeError(f"pytorch-grad-cam {GRADCAM_VERSION} failed for '{method}' on layer "
                           f"'{_layer_name(model, target_layers[0])}': {e}") from e
    finally:
        ag = getattr(cam, "activations_and_grads", None)
        if ag is not None and hasattr(ag, "release"):
            ag.release()
    overlay = show_cam_on_image(rgb_float, gray, use_rgb=True)
    return gray, overlay


def generate_explanation(model: nn.Module, image, method: str, target_class=None,
                         model_name: Optional[str] = None) -> Tuple[np.ndarray, np.ndarray]:
    """Public interface: generate_explanation(model, image, method, target_class=None) -> (heatmap, overlay).
    `model` must come from load_checkpoint (carries model.meta with class names / normalization)."""
    meta = getattr(model, "meta", None)
    if not meta or "class_names" not in meta:
        raise ValueError("model.meta missing — load the model with load_checkpoint().")
    model_name = model_name or meta["model_name"]
    tensor, rgb = preprocess_image(image, meta["image_size"], meta["mean"], meta["std"])
    layers = get_target_layers(model, model_name, meta["image_size"], verbose=False)
    return generate_xai(model, tensor, rgb, method, layers, _resolve_target(target_class, meta["class_names"]))

