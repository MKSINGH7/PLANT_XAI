_MODEL_CACHE: Dict[str, Tuple[nn.Module, dict]] = {}


def _get_model(model_name: str, checkpoint_path: Union[str, Path]) -> nn.Module:
    key = str(checkpoint_path)
    if key not in _MODEL_CACHE:
        model, ckpt = load_checkpoint(checkpoint_path)
        if ckpt["model_name"] != model_name:
            raise ValueError(f"Checkpoint holds '{ckpt['model_name']}' but model_name='{model_name}' was requested.")
        _MODEL_CACHE[key] = (model, ckpt)
    return _MODEL_CACHE[key][0]


def predict_image(image_path, model_name: str, checkpoint_path) -> Tuple[str, float, Dict[str, float]]:
    """Returns (predicted_class, confidence, {class_name: probability})."""
    model = _get_model(model_name, checkpoint_path)
