def validate_images(df: pd.DataFrame) -> Tuple[pd.DataFrame, List[Tuple[str, str]]]:
    """Decode every image, record size + content hash, drop unreadable files (and report them)."""
    good, bad = [], []
    for row in tqdm(df.itertuples(index=False), total=len(df), desc="Validating images"):
        try:
            data = Path(row.path).read_bytes()
            md5 = hashlib.md5(data).hexdigest()
            with Image.open(io.BytesIO(data)) as im:
                im.verify()
            with Image.open(io.BytesIO(data)) as im:
                im = im.convert("RGB")
                w, h = im.size
            good.append({**row._asdict(), "md5": md5, "width": w, "height": h})
        except Exception as e:  # noqa: BLE001
            bad.append((row.path, f"{type(e).__name__}: {e}"))
    if not good:
        raise RuntimeError("No readable images remain after validation.")
    out = pd.DataFrame(good)
    print(f"\nReadable images: {len(out)} | corrupted/unreadable: {len(bad)}")
    for p, err in bad[:20]:
        print(f"   BAD: {p} -> {err}")
    if len(bad) > 20:
        print(f"   ... and {len(bad) - 20} more")
    print(f"Resolution range: width {out.width.min()}-{out.width.max()}, height {out.height.min()}-{out.height.max()}")
    cnt = out["class_name"].value_counts()
    ratio = cnt.max() / cnt.min()
    print(f"Class imbalance ratio (max/min): {ratio:.2f}" + ("  -> imbalance present (class weights recommended)" if ratio > 1.5 else ""))
    return out, bad


