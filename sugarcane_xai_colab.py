def extract_dataset(zip_path: Union[str, Path], extract_dir: Union[str, Path], force: bool = False) -> Path:
    """Safely extract a ZIP (blocks path traversal). Re-uses a previous extraction of the same ZIP."""
    zip_path, extract_dir = Path(zip_path), Path(extract_dir)
    print(f"ZIP path            : {zip_path}")
    print(f"Extraction directory: {extract_dir}")
    if not zip_path.exists():
        raise FileNotFoundError(f"ZIP file not found: {zip_path}. Upload it to Colab and update CONFIG['ZIP_PATH'].")
    if not zipfile.is_zipfile(zip_path):
        raise zipfile.BadZipFile(f"Not a valid ZIP file: {zip_path}")
    marker = extract_dir / ".extraction_complete"
    signature = str(zip_path.stat().st_size)
    if marker.exists() and marker.read_text() == signature and not force:
        print("Existing extraction of this ZIP found -> re-using it.")
        return extract_dir
    if extract_dir.exists():
        shutil.rmtree(extract_dir)
    extract_dir.mkdir(parents=True)
    root = extract_dir.resolve()
    with zipfile.ZipFile(zip_path) as zf:
        bad = zf.testzip()
        if bad is not None:
            raise zipfile.BadZipFile(f"Corrupted member inside ZIP: {bad}")
        for member in tqdm(zf.infolist(), desc="Extracting"):
            target = (extract_dir / member.filename).resolve()
            if target != root and root not in target.parents:
                raise ValueError(f"Unsafe path in ZIP (path traversal): {member.filename}")
            zf.extract(member, extract_dir)
    marker.write_text(signature)
    return extract_dir


def discover_dataset(root: Union[str, Path]) -> pd.DataFrame:
    """Recursively locate images and infer class labels from folder structure.

    Rule: every directory that directly contains images is an 'image directory'. Its class is the directory
    name, unless that name is generic ('images', 'data', ...) or a split name ('train', 'val', 'test'), in which
    case we walk up to the parent. Same class name found under several split folders is merged (and reported).
    """
    root = Path(root)
    image_dirs: Dict[Path, List[str]] = {}
    ext_counter: Dict[str, int] = {}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if not d.startswith(".") and d != "__MACOSX"]
        imgs = [f for f in filenames if not f.startswith(".") and Path(f).suffix.lower() in IMG_EXT]
        for f in imgs:
            e = Path(f).suffix.lower()
            ext_counter[e] = ext_counter.get(e, 0) + 1
        if imgs:
            image_dirs[Path(dirpath)] = imgs
    if not image_dirs:
        raise RuntimeError(f"No image files ({sorted(IMG_EXT)}) found under {root}.")

    records, depths, split_dirs_seen = [], set(), set()
    for d, files in image_dirs.items():
        label_dir = d
        while label_dir != root and label_dir.name.lower() in (GENERIC_DIR_NAMES | SPLIT_DIR_NAMES):
            label_dir = label_dir.parent
        if label_dir == root:
            raise RuntimeError(
                f"Images found in '{d}' but no class folder could be inferred (images sit directly in the "
                f"dataset root or only in generic/split-named folders). Expected class_name/image.jpg layout.")
        rel_parts = [p.lower() for p in d.relative_to(root).parts]
        src_split = next((p for p in rel_parts if p in SPLIT_DIR_NAMES), "")
        if src_split:
            split_dirs_seen.add(src_split)
        depths.add(len(label_dir.relative_to(root).parts))
        for f in files:
            records.append({"path": str(d / f), "class_name": label_dir.name,
                            "source_split": src_split, "source_dir": str(d.relative_to(root))})
    df = pd.DataFrame(records).sort_values("path").reset_index(drop=True)

    n_cls = df["class_name"].nunique()
    if n_cls < 2:
        raise RuntimeError(f"Only {n_cls} class folder detected ({df['class_name'].unique()}); need >= 2.")

    print("\n=== DATASET STRUCTURE ===")
    print(f"Dataset root           : {root}")
    print(f"Class-folder depth(s)  : {sorted(depths)} level(s) below the root")
    print(f"Pre-existing split dirs: {sorted(split_dirs_seen) or 'none'}"
          + ("  -> images will be POOLED and re-split by this pipeline." if split_dirs_seen else ""))
    print(f"Image extensions found : {ext_counter}")
    print(f"Discovered class folders ({n_cls}):")
    counts = df["class_name"].value_counts().sort_index()
    for name, c in counts.items():
        print(f"   {name:<40s} {c:>6d} images")
    print(f"Total images           : {len(df)}")
    if n_cls != 9:
        print(f"NOTE: synopsis describes 9 classes (8 diseases + healthy) but {n_cls} were discovered. "
              f"Check the class list above before trusting results.")
    return df


