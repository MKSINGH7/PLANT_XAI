class FocalLoss(nn.Module):
    """Multi-class focal loss with optional class weights."""

    def __init__(self, gamma: float = 2.0, weight: Optional[torch.Tensor] = None):
        super().__init__()
        self.gamma, self.weight = gamma, weight

    def forward(self, logits, target):
        logp = F.log_softmax(logits.float(), dim=1)
        ce = F.nll_loss(logp, target, weight=self.weight, reduction="none")
        pt = torch.exp(-F.nll_loss(logp, target, reduction="none"))
        return ((1 - pt) ** self.gamma * ce).mean()


def make_scaler(enabled: bool):
    try:
        return torch.amp.GradScaler("cuda", enabled=enabled)
    except (AttributeError, TypeError):
        return torch.cuda.amp.GradScaler(enabled=enabled)


def train_one_epoch(model, loader, criterion, optimizer, scaler, use_amp: bool) -> Tuple[float, float]:
    model.train()
    total_loss, correct, n = 0.0, 0, 0
    for x, y in tqdm(loader, desc="  train", leave=False):
        x, y = x.to(device, non_blocking=True), y.to(device, non_blocking=True)
        optimizer.zero_grad(set_to_none=True)
        with torch.autocast(device_type=device.type, enabled=use_amp):
            logits = model(x)
            loss = criterion(logits, y)
        scaler.scale(loss).backward()
        scaler.unscale_(optimizer)
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        scaler.step(optimizer)
        scaler.update()
        total_loss += loss.item() * x.size(0)
        correct += (logits.argmax(1) == y).sum().item()
        n += x.size(0)
    return total_loss / n, correct / n


@torch.no_grad()
def predict_loader(model, loader, criterion=None, use_amp: bool = False):
    """Returns (loss|None, y_true, y_pred, probs[N,C])."""
    model.eval()
    ys, ps, probs, total_loss, n = [], [], [], 0.0, 0
    for x, y in tqdm(loader, desc="  eval ", leave=False):
        x, y = x.to(device, non_blocking=True), y.to(device, non_blocking=True)
        with torch.autocast(device_type=device.type, enabled=use_amp):
            logits = model(x)
        if criterion is not None:
            total_loss += criterion(logits.float(), y).item() * x.size(0)
        n += x.size(0)
        pr = torch.softmax(logits.float(), 1)
        probs.append(pr.cpu().numpy())
        ps.append(pr.argmax(1).cpu().numpy())
        ys.append(y.cpu().numpy())
    return (total_loss / n if criterion is not None else None), np.concatenate(ys), np.concatenate(ps), np.concatenate(probs)


def validate_one_epoch(model, loader, criterion, use_amp: bool) -> Dict[str, float]:
    loss, yt, yp, _ = predict_loader(model, loader, criterion, use_amp)
    _, _, f1, _ = precision_recall_fscore_support(yt, yp, average="macro", zero_division=0)
    return {"loss": loss, "acc": accuracy_score(yt, yp), "macro_f1": f1}


def save_checkpoint(path: Path, model, model_name: str, class_names: List[str], val_metric: float,
                    epoch: int, cfg: dict = CONFIG, extra: Optional[dict] = None) -> None:
    ckpt = {
        "model_name": model_name,
        "timm_name": resolve_timm_name(model_name, cfg),
        "class_names": list(class_names),
        "state_dict": {k: v.detach().cpu() for k, v in model.state_dict().items()},
        "image_size": cfg["IMAGE_SIZE"],
        "normalization": {"mean": IMAGENET_MEAN, "std": IMAGENET_STD},
        "config": json.loads(json.dumps(cfg, default=str)),
        "val_metric": {"name": "val_macro_f1", "value": float(val_metric)},
        "epoch": int(epoch),
        "timm_version": timm.__version__, "torch_version": torch.__version__,
    }
    if extra:
        ckpt.update(extra)
    path.parent.mkdir(parents=True, exist_ok=True)
    torch.save(ckpt, path)


def load_checkpoint(path: Union[str, Path]) -> Tuple[nn.Module, dict]:
    """Rebuild the architecture from the checkpoint, load weights, attach `model.meta`, return (model, ckpt)."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Checkpoint not found: {path}")
    try:
        ckpt = torch.load(path, map_location="cpu", weights_only=False)
    except TypeError:
        ckpt = torch.load(path, map_location="cpu")
    model = create_model(ckpt["model_name"], len(ckpt["class_names"]), pretrained=False)
    model.load_state_dict(ckpt["state_dict"])
    model.to(device).eval()
    model.meta = {"model_name": ckpt["model_name"], "timm_name": ckpt["timm_name"],
                  "class_names": ckpt["class_names"], "image_size": ckpt["image_size"],
                  "mean": ckpt["normalization"]["mean"], "std": ckpt["normalization"]["std"]}
    return model, ckpt


def train_model(model_name: str, train_df: pd.DataFrame, val_df: pd.DataFrame, class_names: List[str],
                ckpt_path: Path, tag: str, cfg: dict = CONFIG) -> dict:
    """Fine-tune one model; checkpoint on best validation macro-F1; early stopping; cosine LR schedule."""
    set_seed(cfg["SEED"], cfg["DETERMINISTIC"])
    print(f"\n{'=' * 70}\nTRAINING {tag} | train={len(train_df)} val={len(val_df)} | device={device}\n{'=' * 70}")
    model = create_model(model_name, len(class_names), cfg["PRETRAINED"], cfg).to(device)
    train_loader, val_loader = make_loader(train_df, True, cfg), make_loader(val_df, False, cfg)
    weights = compute_class_weights(train_df, len(class_names)).to(device) if cfg["USE_CLASS_WEIGHTS"] else None
    criterion = FocalLoss(cfg["FOCAL_GAMMA"], weights) if cfg["USE_FOCAL_LOSS"] else nn.CrossEntropyLoss(weight=weights)
    optimizer = torch.optim.AdamW(model.parameters(), lr=cfg["LEARNING_RATE"], weight_decay=cfg["WEIGHT_DECAY"])
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=cfg["NUM_EPOCHS"], eta_min=cfg["LEARNING_RATE"] * 0.01)
    scaler = make_scaler(USE_AMP)

    hist, best_f1, best_epoch, bad_epochs = [], -1.0, 0, 0
    for epoch in range(1, cfg["NUM_EPOCHS"] + 1):
        t0 = time.time()
        tr_loss, tr_acc = train_one_epoch(model, train_loader, criterion, optimizer, scaler, USE_AMP)
        val = validate_one_epoch(model, val_loader, criterion, USE_AMP)
        lr = optimizer.param_groups[0]["lr"]
        scheduler.step()
        hist.append({"epoch": epoch, "train_loss": tr_loss, "train_acc": tr_acc, "val_loss": val["loss"],
                     "val_acc": val["acc"], "val_macro_f1": val["macro_f1"], "lr": lr})
        improved = val["macro_f1"] > best_f1
        if improved:
            best_f1, best_epoch, bad_epochs = val["macro_f1"], epoch, 0
            save_checkpoint(ckpt_path, model, model_name, class_names, best_f1, epoch, cfg)
        else:
            bad_epochs += 1
        print(f"[{tag}] ep {epoch:02d}/{cfg['NUM_EPOCHS']} | loss {tr_loss:.4f}/{val['loss']:.4f} | "
              f"acc {tr_acc:.4f}/{val['acc']:.4f} | val F1 {val['macro_f1']:.4f}{' *' if improved else ''} | {time.time() - t0:.0f}s")
        if bad_epochs >= cfg["EARLY_STOP_PATIENCE"]:
            print(f"Early stopping at epoch {epoch} (best epoch {best_epoch}, val macro-F1 {best_f1:.4f}).")
            break
    history = pd.DataFrame(hist)
    history.to_csv(DIRS["results"] / f"{tag}_history.csv", index=False)
    plot_training_history(history, tag)
    del model, optimizer
    if device.type == "cuda":
        torch.cuda.empty_cache()
    return {"tag": tag, "ckpt_path": str(ckpt_path), "best_val_f1": best_f1, "best_epoch": best_epoch, "history": history}


def plot_training_history(history: pd.DataFrame, tag: str) -> Path:
    fig, ax = plt.subplots(1, 2, figsize=(12, 4))
    ax[0].plot(history.epoch, history.train_loss, label="train loss")
    ax[0].plot(history.epoch, history.val_loss, label="validation loss")
    ax[0].set(title=f"{tag} — loss", xlabel="epoch", ylabel="loss"); ax[0].legend(); ax[0].grid(alpha=.3)
    ax[1].plot(history.epoch, history.train_acc, label="train accuracy")
    ax[1].plot(history.epoch, history.val_acc, label="validation accuracy")
    ax[1].set(title=f"{tag} — accuracy", xlabel="epoch", ylabel="accuracy"); ax[1].legend(); ax[1].grid(alpha=.3)
    fig.tight_layout()
    path = DIRS["plots"] / f"{tag}_training_curves.png"
    fig.savefig(path, dpi=150); plt.show(); plt.close(fig)
    return path


def plot_confusion_matrix(cm: np.ndarray, class_names: List[str], title: str, path: Path) -> None:
    cmn = cm / np.maximum(cm.sum(1, keepdims=True), 1)
    fig, ax = plt.subplots(figsize=(0.9 * len(class_names) + 3, 0.8 * len(class_names) + 2.5))
    im = ax.imshow(cmn, cmap="Blues", vmin=0, vmax=1)
    ax.set_xticks(range(len(class_names))); ax.set_yticks(range(len(class_names)))
    ax.set_xticklabels(class_names, rotation=45, ha="right"); ax.set_yticklabels(class_names)
    for i in range(len(class_names)):
        for j in range(len(class_names)):
            ax.text(j, i, int(cm[i, j]), ha="center", va="center", color="white" if cmn[i, j] > .5 else "black", fontsize=8)
    ax.set(title=f"{title}\n(cell = count, colour = row-normalised)", xlabel="Predicted", ylabel="True")
    fig.colorbar(im, ax=ax, fraction=0.046); fig.tight_layout()
    fig.savefig(path, dpi=150); plt.show(); plt.close(fig)


def evaluate_model(ckpt_path: Union[str, Path], test_df: pd.DataFrame, tag: str, cfg: dict = CONFIG) -> dict:
    """Evaluate a checkpoint on the held-out test set; saves CSVs + confusion-matrix plot."""
    model, ckpt = load_checkpoint(ckpt_path)
    cn = ckpt["class_names"]
    _, yt, yp, _ = predict_loader(model, make_loader(test_df, False, cfg), None, USE_AMP)
    p, r, f1, _ = precision_recall_fscore_support(yt, yp, average="macro", zero_division=0)
    metrics = {"Model": tag, "Accuracy": accuracy_score(yt, yp), "Macro Precision": p, "Macro Recall": r, "Macro F1": f1,
               "N_test": len(yt)}
    labels = list(range(len(cn)))
    cm = confusion_matrix(yt, yp, labels=labels)
    report = pd.DataFrame(classification_report(yt, yp, labels=labels, target_names=cn, output_dict=True, zero_division=0)).T
    pd.DataFrame([metrics]).to_csv(DIRS["results"] / f"{tag}_test_metrics.csv", index=False)
    report.to_csv(DIRS["results"] / f"{tag}_classification_report.csv")
    pd.DataFrame(cm, index=cn, columns=cn).to_csv(DIRS["results"] / f"{tag}_confusion_matrix.csv")
    plot_confusion_matrix(cm, cn, f"{tag} — test confusion matrix", DIRS["plots"] / f"{tag}_confusion_matrix.png")
    print(f"\n--- {tag}: per-class report (test) ---\n{report.round(4).to_string()}")
    del model
    return {"metrics": metrics, "cm": cm, "report": report}


