def run_model_training(model_name: str, split_df: pd.DataFrame, class_names: List[str], cfg: dict = CONFIG) -> dict:
    """Single train/val run, or stratified group 5-fold CV over the train+val pool (test set stays untouched)."""
    ck_dir = DIRS["checkpoints"]
    train_df, val_df = split_df[split_df.split == "train"], split_df[split_df.split == "val"]
    if not cfg["USE_5_FOLD_CV"]:
        run = train_model(model_name, train_df, val_df, class_names, ck_dir / f"{model_name}_best.pth", model_name, cfg)
        return {"runs": [run], "selected_ckpt": run["ckpt_path"]}
    pool = split_df[split_df.split.isin(["train", "val"])].reset_index(drop=True)
    skf = StratifiedGroupKFold(n_splits=cfg["N_FOLDS"], shuffle=True, random_state=cfg["SEED"])
    runs = []
    for k, (tr, va) in enumerate(skf.split(pool, pool["label"], pool["group_id"]), start=1):
        runs.append(train_model(model_name, pool.iloc[tr], pool.iloc[va], class_names,
                                ck_dir / f"{model_name}_fold{k}_best.pth", f"{model_name}_fold{k}", cfg))
    best = max(runs, key=lambda r: r["best_val_f1"])          # selected by VALIDATION metric only
    shutil.copy(best["ckpt_path"], ck_dir / f"{model_name}_best.pth")
    print(f"CV: checkpoint of {best['tag']} (highest validation macro-F1) saved as {model_name}_best.pth")
    return {"runs": runs, "selected_ckpt": str(ck_dir / f"{model_name}_best.pth")}

